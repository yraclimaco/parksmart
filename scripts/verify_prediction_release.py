"""Verify a private local release through Daira's backend with fitting forbidden.

Only summary values are printed; no pickle contents or source observations are
exposed. This command uses local files and disables routing/provider calls.
"""

import argparse
import json
import os
from pathlib import Path
from unittest.mock import patch

from fastapi.testclient import TestClient

from src.api import saved_model
from src.api.bundle import FILENAMES, file_sha256, validate_manifest
from src.parking_benchmarks import HistoricalAverage

SMOKE_REQUEST = {
    "destination": {"name": "UCSD", "coordinates": {
        "latitude": 32.8811, "longitude": -117.2376}},
    "arrival_time": "2026-11-03T10:00:00", "permit_type": "S",
}


def verify_release(release_dir):
    """Check local bundle integrity and return a no-training backend summary.

    Args:
        release_dir: Private bundle directory generated by prepare_serving_bundle.
    Returns:
        JSON-compatible readiness, load count and distinct recommended IDs.
        Missing/incompatible resources, changed bytes or unavailable choices raise.
    """
    release_dir = Path(release_dir).resolve()
    manifest = json.loads((release_dir / "manifest.json").read_text())
    artifact_key = manifest["files"]["artifact"]["key"]
    prefix = artifact_key.rsplit("/", 1)[0] + "/"
    files = validate_manifest(manifest, prefix)
    for role, filename in FILENAMES.items():
        if file_sha256(release_dir / filename) != files[role]["sha256"]:
            raise ValueError(f"Local {role} checksum mismatch")
    if "release_metadata" in manifest:
        if file_sha256(release_dir / "metadata.json") != (
                manifest["release_metadata"]["sha256"]):
            raise ValueError("Local metadata checksum mismatch")
    environment = {
        "PARKSMART_MODEL_MODE": "saved",
        "PARKSMART_APPROVED_MODEL": "historical_average",
        "PARKSMART_ARTIFACT_PATH": str(release_dir / "selected.pkl"),
        "PARKSMART_DATASET_PATH": str(release_dir / "analysis_dataset.csv"),
        "PARKSMART_REGISTRY_PATH": str(release_dir / "locations.json"),
        "PARKSMART_ROUTING_PROVIDER": "none",
    }
    with (
        patch.dict(os.environ, environment),
        patch.object(HistoricalAverage, "fit",
                     side_effect=AssertionError("Serving fitted")),
        patch.object(saved_model, "load_prediction_service",
                     wraps=saved_model.load_prediction_service) as loads,
    ):
        os.environ.pop("PARKSMART_BUNDLE_MANIFEST", None)
        with TestClient(saved_model.create_configured_app()) as client:
            readiness = client.get("/readiness")
            if readiness.status_code != 200:
                raise RuntimeError(f"Release is not ready: {readiness.json()}")
            choices = []
            for _ in range(2):  # Both requests must reuse the single startup load.
                response = client.post("/recommendations", json=SMOKE_REQUEST)
                body = response.json()
                if response.status_code != 200 or body.get("status") != "ready":
                    raise RuntimeError("Supported smoke request has no ready result")
                first, backup = body.get("first_choice"), body.get("backup_choice")
                if not first or not backup:
                    raise RuntimeError("Smoke request needs first and backup choices")
                ids = [choice["location"]["location_id"] for choice in (first, backup)]
                if ids[0] == ids[1]:
                    raise RuntimeError("First choice and backup must be distinct")
                choices.append(ids)
            if loads.call_count != 1:
                raise RuntimeError("Saved artifact must load exactly once per startup")
    return {"readiness": readiness.json(), "artifact_loads": loads.call_count,
            "recommendation_requests": len(choices), "choices": choices,
            "training_allowed": False, "routing_enabled": False}


def main(argv=None):
    """Parse --release-dir from optional arguments, print and return the summary."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    result = verify_release(args.release_dir)
    print(json.dumps(result, indent=2))
    return result


if __name__ == "__main__":
    main()
